#!/bin/sh
# Materialise a self-contained copy of the (patched) Zipp engine under
# vendor/engine, so the gem can be built and shipped OUTSIDE this checkout.
#
# The development tree uses the `vendor/zipp` submodule + patches/ (see
# scripts/apply-patches.sh). The native extension's Cargo.toml path-depends on
# vendor/engine/crates/zipp-vm; this script regenerates it from the submodule
# (picking up any applied patches), excluding tests to keep it small. vendor/
# engine is generated and git-ignored; the packaging step (rake build) runs this
# first so the produced .gem is self-contained.
set -eu

root="$(cd "$(dirname "$0")/.." && pwd)"
src="$root/vendor/zipp"
dst="$root/vendor/engine"
crates="zipp-vm regress-fork zipp-numparse zipp-pyparse"

if [ ! -d "$src/crates/zipp-vm" ]; then
    echo "vendor/zipp is missing; run: git submodule update --init && scripts/apply-patches.sh" >&2
    exit 1
fi

head="$(git -C "$src" rev-parse HEAD 2>/dev/null || echo unknown)"
stamp="$dst/.engine-rev"

if [ -d "$dst/crates/zipp-vm" ] && [ -f "$stamp" ] && [ "$(cat "$stamp")" = "$head" ]; then
    echo "vendor/engine is up to date ($head)"
    exit 0
fi

rm -rf "$dst"
mkdir -p "$dst/crates"
for c in $crates; do
    mkdir -p "$dst/crates/$c"
    (cd "$src/crates/$c" && tar cf - --exclude tests --exclude target .) |
        (cd "$dst/crates/$c" && tar xf -)
done

cat > "$dst/Cargo.toml" <<'EOF'
# Generated by scripts/vendor-engine.sh — a minimal workspace root so the
# vendored engine crates resolve their `version.workspace`/`dependencies.
[workspace]
resolver = "2"
members = [
    "crates/zipp-vm",
    "crates/regress-fork",
    "crates/zipp-numparse",
    "crates/zipp-pyparse",
]

[workspace.package]
version = "0.0.23"
edition = "2021"
license = "Apache-2.0"

[workspace.dependencies]
rustc-hash = "2"
dynasm = "5.1"
dynasmrt = "5.1"
EOF

echo "$head" > "$stamp"
echo "vendored engine -> vendor/engine ($head)"
